using YoutubeHDx.Core;

namespace YoutubeHDx.Tests;

internal static class CookieFileTests
{
    private static string Write(params BrowserCookie[] cookies)
    {
        var path = Path.Combine(TestEnv.Root, $"cookies-{Guid.NewGuid():N}.txt");
        CookieFile.WriteNetscape(path, cookies);
        return File.ReadAllText(path);
    }

    [Test]
    public static void WritesNetscapeHeaderAndHttpOnlyPrefix()
    {
        var text = Write(new BrowserCookie(".youtube.com", false, "/", true, true, false, 1800000000.7, "SID", "abc"));
        Assert.True(text.StartsWith("# Netscape HTTP Cookie File"));
        Assert.Contains("#HttpOnly_.youtube.com\tTRUE\t/\tTRUE\t1800000000\tSID\tabc\n", text);
    }

    [Test]
    public static void HostOnlyCookieHasNoLeadingDot()
    {
        var text = Write(new BrowserCookie("www.youtube.com", true, "/", true, false, false, 1800000000, "PREF", "x"));
        Assert.Contains("www.youtube.com\tFALSE\t/\tTRUE\t1800000000\tPREF\tx\n", text);
    }

    [Test]
    public static void DomainCookieGetsLeadingDot()
    {
        var text = Write(new BrowserCookie("youtube.com", false, "/", false, false, false, 1800000000, "A", "1"));
        Assert.Contains(".youtube.com\tTRUE\t/\tFALSE\t", text);
    }

    [Test]
    public static void SessionCookieExpiresZero()
    {
        var text = Write(new BrowserCookie(".youtube.com", false, "/", true, false, true, null, "YSC", "s"));
        Assert.Contains("\t0\tYSC\ts\n", text);
    }

    [Test]
    public static void SkipsCookiesThatWouldBreakTheFormat()
    {
        var text = Write(
            new BrowserCookie(".youtube.com", false, "/", true, false, true, null, "BAD", "a\tb"),
            new BrowserCookie(".youtube.com", false, "/", true, false, true, null, "", "noname"),
            new BrowserCookie(".youtube.com", false, "/", true, false, true, null, "GOOD", "ok"));
        Assert.False(text.Contains("BAD"));
        Assert.False(text.Contains("noname"));
        Assert.Contains("GOOD\tok", text);
    }

    [Test]
    public static void HasLoginOnlyWithLoginInfoCookie()
    {
        var path = Path.Combine(TestEnv.Root, $"login-{Guid.NewGuid():N}.txt");
        Assert.False(CookieFile.HasLogin(path)); // missing file

        CookieFile.WriteNetscape(path, [new BrowserCookie(".youtube.com", false, "/", true, false, true, null, "PREF", "x")]);
        Assert.False(CookieFile.HasLogin(path)); // signed out

        CookieFile.WriteNetscape(path, [new BrowserCookie(".youtube.com", false, "/", true, true, false, 1800000000, "LOGIN_INFO", "x")]);
        Assert.True(CookieFile.HasLogin(path)); // HttpOnly-prefixed line still counts
    }

    [Test]
    public static void RequireLoginIsOnByDefault() => Assert.True(new AppSettings().RequireLogin);

    [Test]
    public static void EmptyPathBecomesSlash()
    {
        var text = Write(new BrowserCookie(".youtube.com", false, "", true, false, true, null, "P", "v"));
        Assert.Contains(".youtube.com\tTRUE\t/\tTRUE\t0\tP\tv", text);
    }
}

internal static class YtDlpArgsTests
{
    private static AppSettings Settings() => new() { NasPath = @"\\nas\yt", TempPath = @"C:\tmp\yhdx" };

    private static List<string> Build(AppSettings? s = null, bool noPlaylist = true, string? cookies = null) =>
        YtDlpArgs.Build(s ?? Settings(), new DownloadJob { Url = "https://www.youtube.com/watch?v=abc", NoPlaylist = noPlaylist }, cookies);

    private static string? ValueAfter(List<string> args, string flag)
    {
        var i = args.IndexOf(flag);
        return i >= 0 && i + 1 < args.Count ? args[i + 1] : null;
    }

    [Test]
    public static void RequestsUpTo4kAndMergesToMkv()
    {
        var a = Build();
        Assert.Equal("bv*[height<=2160]+ba/b[height<=2160]/bv*+ba/b", ValueAfter(a, "-f"));
        Assert.Equal("res:2160,fps", ValueAfter(a, "-S"));
        Assert.Equal("mkv", ValueAfter(a, "--merge-output-format"));
        Assert.Equal("mkv", ValueAfter(a, "--remux-video"));
    }

    [Test]
    public static void MaxHeightIsConfigurable()
    {
        var a = Build(new AppSettings { NasPath = "n", TempPath = "t", MaxHeight = 1440 });
        Assert.Equal("bv*[height<=1440]+ba/b[height<=1440]/bv*+ba/b", ValueAfter(a, "-f"));
    }

    [Test]
    public static void NeverAsksForAutoGeneratedCaptions()
    {
        var a = Build();
        Assert.Contains("--no-write-auto-subs", a);
        Assert.DoesNotContain("--write-auto-subs", a);
        Assert.DoesNotContain("--write-automatic-subs", a);
        Assert.Equal("en.*,-live_chat", ValueAfter(a, "--sub-langs"));
        Assert.Equal("srt", ValueAfter(a, "--convert-subs"));
    }

    [Test]
    public static void SubtitleFlagCombinations()
    {
        var embedAndKeep = Build(new AppSettings { NasPath = "n", TempPath = "t", EmbedSubtitles = true, KeepSubtitleFiles = true });
        Assert.Contains("--embed-subs", embedAndKeep);
        Assert.Contains("--write-subs", embedAndKeep);

        var embedOnly = Build(new AppSettings { NasPath = "n", TempPath = "t", EmbedSubtitles = true, KeepSubtitleFiles = false });
        Assert.Contains("--embed-subs", embedOnly);
        Assert.DoesNotContain("--write-subs", embedOnly);

        var sidecarOnly = Build(new AppSettings { NasPath = "n", TempPath = "t", EmbedSubtitles = false });
        Assert.DoesNotContain("--embed-subs", sidecarOnly);
        Assert.Contains("--write-subs", sidecarOnly);
    }

    [Test]
    public static void DownloadsToTempThenMovesToNas()
    {
        var a = Build();
        Assert.Contains(@"home:\\nas\yt", a);
        Assert.Contains(@"temp:C:\tmp\yhdx", a);
        Assert.Equal(Path.Combine(@"\\nas\yt", ".youtubehdx-archive.txt"), ValueAfter(a, "--download-archive"));
    }

    [Test]
    public static void PlaylistFlagFollowsJob()
    {
        Assert.Contains("--no-playlist", Build(noPlaylist: true));
        Assert.Contains("--yes-playlist", Build(noPlaylist: false));
        Assert.DoesNotContain("--no-playlist", Build(noPlaylist: false));
    }

    [Test]
    public static void CookiesOnlyPassedWhenFileExists()
    {
        Assert.DoesNotContain("--cookies", Build(cookies: Path.Combine(TestEnv.Root, "missing.txt")));

        var file = Path.Combine(TestEnv.Root, "present-cookies.txt");
        File.WriteAllText(file, "# Netscape HTTP Cookie File\n");
        Assert.Equal(file, ValueAfter(Build(cookies: file), "--cookies"));
    }

    [Test]
    public static void UrlIsLastAndSeparatedByDoubleDash()
    {
        var a = Build();
        Assert.Equal("--", a[^2]);
        Assert.Equal("https://www.youtube.com/watch?v=abc", a[^1]);
    }

    [Test]
    public static void ExtraArgsAreInsertedBeforeUrl()
    {
        var s = Settings();
        s.ExtraArgs = "--extractor-args \"youtube:player_client=default,web\" --limit-rate 5M";
        var a = Build(s);
        Assert.Equal("youtube:player_client=default,web", ValueAfter(a, "--extractor-args"));
        Assert.True(a.IndexOf("--limit-rate") < a.IndexOf("--"));
    }

    [Test]
    public static void FfmpegLocationOnlyWhenSet()
    {
        Assert.DoesNotContain("--ffmpeg-location", Build());
        var s = Settings();
        s.FfmpegLocation = @"C:\ffmpeg\bin";
        Assert.Equal(@"C:\ffmpeg\bin", ValueAfter(Build(s), "--ffmpeg-location"));
    }

    [Test]
    public static void SplitCommandLineHandlesQuotes()
    {
        var parts = YtDlpArgs.SplitCommandLine("  -a  \"b c\" d\"e f\"g \"\" ").ToList();
        Assert.Equal(4, parts.Count);
        Assert.Equal("-a", parts[0]);
        Assert.Equal("b c", parts[1]);
        Assert.Equal("de fg", parts[2]);
        Assert.Equal("", parts[3]);
        Assert.Equal(0, YtDlpArgs.SplitCommandLine("   ").Count());
        Assert.Equal(0, YtDlpArgs.SplitCommandLine(null).Count());
    }
}

internal static class SettingsTests
{
    [Test]
    public static void CreatesDefaultsOnFirstLoad()
    {
        if (File.Exists(AppPaths.SettingsFile)) File.Delete(AppPaths.SettingsFile);
        var s = SettingsStore.Load();
        Assert.True(File.Exists(AppPaths.SettingsFile));
        Assert.Equal(2160, s.MaxHeight);
        Assert.Contains("\"nasPath\"", File.ReadAllText(AppPaths.SettingsFile));
    }

    [Test]
    public static void RoundTripsAndToleratesCommentsAndTrailingCommas()
    {
        File.WriteAllText(AppPaths.SettingsFile, """
            {
              // where videos go
              "NasPath": "Z:\\YouTube",
              "maxHeight": 1440,
              "watchedPlaylists": [ { "url": "https://www.youtube.com/playlist?list=PL1" }, ],
            }
            """);
        var s = SettingsStore.Load();
        Assert.Equal(@"Z:\YouTube", s.NasPath);
        Assert.Equal(1440, s.MaxHeight);
        Assert.Equal(1, s.WatchedPlaylists.Count);
        Assert.True(s.WatchedPlaylists[0].Enabled);
    }

    [Test]
    public static void InvalidJsonGivesAClearError()
    {
        File.WriteAllText(AppPaths.SettingsFile, "{ not json");
        var ex = Assert.Throws<InvalidOperationException>(() => SettingsStore.Load());
        Assert.Contains("settings.json is not valid JSON", ex.Message);
        File.Delete(AppPaths.SettingsFile);
    }

    [Test]
    public static void AddWatchedPlaylistIsIdempotent()
    {
        SettingsStore.Save(new AppSettings());
        Assert.True(SettingsStore.AddWatchedPlaylist("https://www.youtube.com/playlist?list=PLx"));
        Assert.False(SettingsStore.AddWatchedPlaylist("https://www.youtube.com/playlist?list=plx".Replace("plx", "PLx")));
        Assert.Equal(1, SettingsStore.Load().WatchedPlaylists.Count);
    }
}
