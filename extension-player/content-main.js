// MAIN world: talks to YouTube's own player object (#movie_player) to force quality and pick captions.
// These player methods are not an official API; if YouTube renames them this script simply does nothing.
(() => {
  'use strict';

  const QUALITY_ORDER = ['highres', 'hd2880', 'hd2160', 'hd1440', 'hd1080', 'hd720', 'large', 'medium', 'small', 'tiny'];
  const RETRY_MS = 500;
  const MAX_ATTEMPTS = 40;          // ~20 s per video
  const CAPTION_GIVE_UP = 12;       // ~6 s waiting for a track list => video has no captions

  let settings = null;
  let captionCss = '';
  let timer = null;
  let state = freshState(null);

  function freshState(videoId) {
    return { videoId, qualityDone: false, captionsDone: false, attempts: 0, sawAd: false };
  }

  const getPlayer = () => document.getElementById('movie_player');
  const isWatchPage = () => /^\/(watch|shorts\/|embed\/|live\/)/.test(location.pathname);

  // ---------- quality ----------

  function pickQuality(available, wanted) {
    const levels = (available || []).filter((q) => QUALITY_ORDER.includes(q));
    if (!levels.length) return null;
    const wantIdx = Math.max(0, QUALITY_ORDER.indexOf(wanted));
    // Best level at or below the wanted one; otherwise the lowest the video has.
    const ok = levels.filter((q) => QUALITY_ORDER.indexOf(q) >= wantIdx)
                     .sort((a, b) => QUALITY_ORDER.indexOf(a) - QUALITY_ORDER.indexOf(b));
    return ok[0] ?? levels.sort((a, b) => QUALITY_ORDER.indexOf(b) - QUALITY_ORDER.indexOf(a))[0];
  }

  function applyQuality(p) {
    if (!settings.forceQuality) return true;
    if (typeof p.getAvailableQualityLevels !== 'function') return false;
    const target = pickQuality(p.getAvailableQualityLevels(), settings.quality);
    if (!target) return false; // levels not loaded yet
    p.setPlaybackQualityRange?.(target, target);
    p.setPlaybackQuality?.(target);
    return true;
  }

  // ---------- captions ----------

  const isAutoGenerated = (t) => t.kind === 'asr' || /^a\./.test(t.vss_id || t.vssId || '');

  function captionsOff(p) {
    try { p.setOption?.('captions', 'track', {}); } catch { /* ignore */ }
    p.unloadModule?.('captions');
  }

  function applyCaptions(p) {
    if (settings.captions === 'leave') return true;
    if (settings.captions === 'off') { captionsOff(p); return true; }
    if (typeof p.getOption !== 'function') return false;

    let tracks = [];
    try { tracks = p.getOption('captions', 'tracklist', { includeAsr: true }) || []; } catch { /* module not loaded */ }

    if (!tracks.length) {
      p.loadModule?.('captions'); // track list is only populated once the captions module is loaded
      if (state.attempts >= CAPTION_GIVE_UP) { captionsOff(p); return true; } // no captions on this video
      return false;
    }

    const manual = tracks.filter((t) => !isAutoGenerated(t));
    const code = (t) => String(t.languageCode || '').toLowerCase();
    let pick = null;
    for (const lang of settings.captionLanguages || []) {
      pick = manual.find((t) => code(t) === String(lang).toLowerCase());
      if (pick) break;
    }
    pick ??= manual.find((t) => code(t).startsWith('en'));

    if (pick) {
      p.setOption('captions', 'track', pick);
      lastPick = { videoId: state.videoId, track: pick };
    } else {
      captionsOff(p); // only auto-generated English exists: keep captions off
    }
    return true;
  }

  // ---------- caption repair ----------
  // YouTube sometimes answers the caption request with an empty body, aborts it, or never finishes it (its
  // anti-bot token wasn't ready yet, e.g. when the request went out during an ad). The player then shows CC
  // as "on" but draws nothing. Turning CC off and on fixes it by requesting again; we do that automatically.

  const REPAIR_DELAYS_MS = [1500, 4000, 10000];
  const REQUEST_TIMEOUT_MS = 8000;
  let lastPick = null;
  let repair = { videoId: null, attempts: 0, timer: null, failedAt: 0, goodAt: 0 };
  let resultSeq = 0; // orders caption results (two can land in the same millisecond)

  function isEmptyCaptionBody(body) {
    if (body == null) return true;
    if (typeof body === 'string') {
      const text = body.trim();
      if (!text) return true;
      if (text[0] !== '{') return false; // XML/VTT with content
      try { const j = JSON.parse(text); return !Array.isArray(j.events) || j.events.length === 0; } catch { return false; }
    }
    if (body instanceof ArrayBuffer) return body.byteLength === 0;
    if (typeof body === 'object') return !Array.isArray(body.events) || body.events.length === 0;
    return false;
  }

  /** Captions request for the video being watched (not an ad's, never auto-generated)? Returns its video id. */
  function captionRequestVideo(url) {
    let u;
    try { u = new URL(url, location.origin); } catch { return null; }
    if (!u.pathname.endsWith('/api/timedtext') || u.searchParams.get('kind') === 'asr') return null;
    const current = getPlayer()?.getVideoData?.()?.video_id;
    return current && u.searchParams.get('v') === current ? current : null;
  }

  function onCaptionResult(url, ok) {
    const videoId = captionRequestVideo(url);
    if (!videoId) return;
    if (repair.videoId !== videoId) repair = { videoId, attempts: 0, timer: null, failedAt: 0, goodAt: 0 };
    if (ok) { repair.goodAt = ++resultSeq; return; }
    repair.failedAt = ++resultSeq;
    scheduleRepair(videoId);
  }

  function scheduleRepair(videoId) {
    if (!settings || settings.captions === 'off') return;
    if (repair.timer || repair.attempts >= REPAIR_DELAYS_MS.length) return;
    const delay = REPAIR_DELAYS_MS[repair.attempts++];
    repair.timer = setTimeout(() => { repair.timer = null; runRepair(videoId); }, delay);
  }

  function runRepair(videoId) {
    const p = getPlayer();
    if (!p || p.getVideoData?.()?.video_id !== videoId || repair.videoId !== videoId) return;
    if (repair.goodAt > repair.failedAt) return; // a later request brought the captions after all
    if (p.classList.contains('ad-showing')) { repair.attempts--; scheduleRepair(videoId); return; }

    let track = null;
    try { track = p.getOption('captions', 'track'); } catch { /* module not loaded */ }
    if (!track?.languageCode && lastPick?.videoId === videoId) track = lastPick.track;
    if (!track?.languageCode || isAutoGenerated(track)) return; // no proper track selected: nothing to repair

    // Last attempt: reload the video at the same second. The player starts fresh (new token), then we re-apply
    // quality and captions. Only reached when re-requesting twice still brought no captions.
    if (repair.attempts >= REPAIR_DELAYS_MS.length && typeof p.loadVideoById === 'function') {
      const at = Math.max(0, (p.getCurrentTime?.() ?? 0) - 0.5);
      p.loadVideoById({ videoId, startSeconds: at });
      restart();
      return;
    }

    // Same as turning CC off and on: reload the captions module, then select the track again.
    p.unloadModule?.('captions');
    setTimeout(() => {
      p.loadModule?.('captions');
      setTimeout(() => { try { p.setOption('captions', 'track', track); } catch { /* player changed */ } }, 300);
    }, 300);
  }

  // Observe (never change) the player's caption requests.
  (function watchCaptionRequests() {
    const XHR = globalThis.XMLHttpRequest;
    if (XHR?.prototype) {
      const open = XHR.prototype.open;
      const send = XHR.prototype.send;
      XHR.prototype.open = function (method, url, ...rest) {
        try { this.__yhdxUrl = String(url); } catch { /* ignore */ }
        return open.call(this, method, url, ...rest);
      };
      XHR.prototype.send = function (...args) {
        const url = this.__yhdxUrl;
        if (url && url.includes('/api/timedtext')) {
          let settled = false;
          const watchdog = setTimeout(() => { if (!settled) onCaptionResult(url, false); }, REQUEST_TIMEOUT_MS);
          this.addEventListener('loadend', () => {
            settled = true;
            clearTimeout(watchdog);
            let body = null;
            try { body = this.responseType === '' || this.responseType === 'text' ? this.responseText : this.response; } catch { /* ignore */ }
            onCaptionResult(url, this.status >= 200 && this.status < 300 && !isEmptyCaptionBody(body));
          });
        }
        return send.apply(this, args);
      };
    }

    const nativeFetch = globalThis.fetch;
    if (typeof nativeFetch === 'function') {
      globalThis.fetch = function (input, init) {
        const result = nativeFetch.apply(this, arguments);
        const url = typeof input === 'string' ? input : input?.url;
        if (url && url.includes('/api/timedtext')) {
          result.then(
            (r) => r.clone().text().then((t) => onCaptionResult(url, r.ok && !isEmptyCaptionBody(t)), () => onCaptionResult(url, false)),
            () => onCaptionResult(url, false),
          );
        }
        return result;
      };
    }
  })();

  // ---------- caption style ----------

  function applyStyle() {
    let el = document.getElementById('yhdx-caption-style');
    if (!captionCss) { el?.remove(); return; }
    if (!el) {
      el = document.createElement('style');
      el.id = 'yhdx-caption-style';
      (document.head || document.documentElement).appendChild(el);
    }
    if (el.textContent !== captionCss) el.textContent = captionCss;
  }

  // ---------- driver ----------

  function schedule() {
    clearTimeout(timer);
    timer = setTimeout(tick, RETRY_MS);
  }

  function tick() {
    if (!settings || !isWatchPage()) return;
    const p = getPlayer();
    const videoId = p?.getVideoData?.()?.video_id;
    if (!videoId) { schedule(); return; }

    if (videoId !== state.videoId) state = freshState(videoId);
    if (p.classList.contains('ad-showing')) { state.sawAd = true; schedule(); return; } // wait for the real video

    state.attempts++;
    if (!state.qualityDone) state.qualityDone = applyQuality(p);
    if (!state.captionsDone) state.captionsDone = applyCaptions(p);

    if (!(state.qualityDone && state.captionsDone) && state.attempts < MAX_ATTEMPTS) schedule();
  }

  function restart() {
    state = freshState(null);
    schedule();
  }

  window.addEventListener('message', (e) => {
    if (e.source !== window || !e.data || e.data.__yhdx !== 'settings') return;
    settings = e.data.settings;
    captionCss = e.data.captionCss || '';
    applyStyle();
    restart();
  });

  // YouTube is a single-page app: re-apply on every navigation and whenever a new source loads (e.g. after an ad).
  window.addEventListener('yt-navigate-finish', restart);
  document.addEventListener('yt-player-updated', restart);
  document.addEventListener('loadeddata', (e) => {
    if (!(e.target instanceof HTMLVideoElement)) return;
    // Only re-apply for a different video or after an ad; never loop on our own quality switches.
    const id = getPlayer()?.getVideoData?.()?.video_id;
    if (id !== state.videoId || state.sawAd) restart();
  }, true);
  document.addEventListener('DOMContentLoaded', applyStyle);

  window.postMessage({ __yhdx: 'ready' }, location.origin);
})();
